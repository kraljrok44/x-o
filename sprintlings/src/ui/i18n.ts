let lang: Language = 'en';

export function setLanguage(l: Language): void {
  lang = l;
  document.documentElement.lang = l;
}

export function getLanguage(): Language {
  return lang;
}

export function detectLanguage(): Language {
  const n = (navigator.language || 'en').toLowerCase();
  return n.startsWith('sl') ? 'sl' : 'en';
}

export function t(text: string, vars?: Record<string, string | number>): string {
  let out = lang === 'sl' ? SL[text] ?? text : text;
  if (text === 'Back_' && lang !== 'sl') out = 'Back';
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
  return out;
}

/** 1st, 2nd... in English; 1., 2. in Slovene. */
export function ordinal(n: number): string {
  if (lang === 'sl') return `${n}.`;
  const s = n % 10 === 1 && n % 100 !== 11 ? 'st' : n % 10 === 2 && n % 100 !== 12 ? 'nd' : n % 10 === 3 && n % 100 !== 13 ? 'rd' : 'th';
  return `${n}${s}`;
}
